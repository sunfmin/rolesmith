//! `use` and `sync` (SPEC.md §4, §5.1) through the built binary: a role installed into a project
//! for Claude Code, and a fresh clone of the project brought to the same files.

mod common;

use std::collections::BTreeMap;
use std::os::unix::fs::PermissionsExt;
use std::path::Path;

use common::{Machine, published, stderr};

/// Every file under `dir`: its bytes and mode, by its path relative to `dir`.
fn snapshot(dir: &Path) -> BTreeMap<String, (Vec<u8>, u32)> {
    let mut files = BTreeMap::new();
    let mut pending = vec![dir.to_path_buf()];
    while let Some(at) = pending.pop() {
        for entry in std::fs::read_dir(&at).unwrap().flatten() {
            let path = entry.path();
            if path.is_dir() {
                pending.push(path);
            } else {
                let rel = path.strip_prefix(dir).unwrap().to_str().unwrap().to_owned();
                let mode = std::fs::metadata(&path).unwrap().permissions().mode() & 0o777;
                files.insert(rel, (std::fs::read(&path).unwrap(), mode));
            }
        }
    }
    files
}

fn text(dir: &Path, rel: &str) -> String {
    std::fs::read_to_string(dir.join(rel)).unwrap()
}

/// A project's own files, which rolesmith must leave as they are.
fn own_files(project: &Path) {
    let write = |rel: &str, body: &str| {
        let path = project.join(rel);
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, body).unwrap();
    };
    write("CLAUDE.md", "# My project\n\nKeep it small.\n");
    write("AGENTS.md", "Agents: read CLAUDE.md.\n");
    write(
        ".claude/skills/my-own/SKILL.md",
        "---\nname: my-own\ndescription: Mine.\n---\n\nMine.\n",
    );
    write(".gitignore", "/target");
}

#[test]
fn use_writes_exactly_the_generated_files_and_again_changes_nothing() {
    let m = Machine::new();
    let lib = m.library("felix");
    lib.write("library.toml", "name = \"felix\"\n");
    lib.role(
        "app-store-releaser",
        "Ships apps to the App Store",
        "# Core\n\nFirst rule.\n",
    );
    lib.write(
        "roles/app-store-releaser/skills/submit-build/scripts/upload.sh",
        "#!/bin/sh\necho up\n",
    );
    let script = lib
        .work
        .join("roles/app-store-releaser/skills/submit-build/scripts/upload.sh");
    std::fs::set_permissions(&script, std::fs::Permissions::from_mode(0o755)).unwrap();
    let rev = m.publish(&lib, "first");
    m.json(&["source", "add", "felix", lib.url()]);

    let project = m.path("project");
    own_files(&project);
    let own = snapshot(&project);

    let out = m.json(&[
        "use",
        "app-store-releaser",
        "--into",
        "claude-code",
        "--project",
        project.to_str().unwrap(),
    ]);
    assert_eq!(out["roles"][0]["rev"], rev.as_str());

    let after = snapshot(&project);
    let core = ".claude/skills/rolesmith-app-store-releaser/SKILL.md";
    let skill = ".claude/skills/rolesmith-app-store-releaser-submit-build/SKILL.md";
    let upload = ".claude/skills/rolesmith-app-store-releaser-submit-build/scripts/upload.sh";
    let mut expected: Vec<&str> = own.keys().map(String::as_str).collect();
    expected.extend([
        core,
        skill,
        upload,
        ".rolesmith/manifest.json",
        "rolesmith.toml",
    ]);
    expected.sort();
    assert_eq!(
        after.keys().map(String::as_str).collect::<Vec<_>>(),
        expected
    );

    for (rel, before) in &own {
        if rel != ".gitignore" {
            assert_eq!(&after[rel], before, "{rel} was changed");
        }
    }
    let comment = format!(
        "# Generated by rolesmith from felix/app-store-releaser at {rev}; `rolesmith sync` rewrites it, do not edit."
    );
    assert_eq!(
        text(&project, core),
        format!(
            "---\n{comment}\nname: rolesmith-app-store-releaser\n\
             description: \"Always in force in this project: Ships apps to the App Store\"\n---\n\n\
             # Core\n\nFirst rule.\n\n## Prohibitions\n\n\
             - Never revoke a certificate (It breaks other machines)\n"
        )
    );
    assert_eq!(
        text(&project, skill),
        format!(
            "---\n{comment}\nname: rolesmith-app-store-releaser-submit-build\n\
             description: Use when a build is ready for review.\n---\n\nSteps.\n"
        )
    );
    assert_eq!(after[upload], (b"#!/bin/sh\necho up\n".to_vec(), 0o755));
    assert_eq!(
        text(&project, ".rolesmith/manifest.json"),
        format!(
            "{{\n  \"files\": [\n    \"{skill}\",\n    \"{upload}\",\n    \"{core}\"\n  ]\n}}\n"
        )
    );
    assert_eq!(
        text(&project, ".gitignore"),
        "/target\n# rolesmith: generated from rolesmith.toml; `rolesmith sync` rewrites these lines\n\
         /.rolesmith/\n/.claude/skills/rolesmith-app-store-releaser-submit-build/\n\
         /.claude/skills/rolesmith-app-store-releaser/\n# rolesmith: end\n"
    );
    assert_eq!(
        text(&project, "rolesmith.toml"),
        format!(
            "[[role]]\nname = \"app-store-releaser\"\nsource = \"felix\"\nurl = \"{}\"\n\
             rev = \"{rev}\"\ninto = [\"claude-code\"]\n",
            lib.url()
        )
    );

    for again in [&["use", "app-store-releaser"][..], &["sync"][..]] {
        let mut args = again.to_vec();
        if again[0] == "use" {
            args.extend(["--into", "claude-code"]);
        }
        args.extend(["--project", project.to_str().unwrap()]);
        let out = m.json(&args);
        assert_eq!(out["written"], serde_json::json!([]), "{again:?}");
        assert_eq!(snapshot(&project), after, "{again:?} changed the project");
    }
}

#[test]
fn a_fresh_clone_with_only_rolesmith_toml_syncs_to_the_same_files() {
    let m = Machine::new();
    let (lib, _) = published(&m, "felix", &["app-store-releaser"]);
    m.json(&["source", "add", "felix", lib.url()]);
    let project = m.path("project");
    std::fs::create_dir_all(&project).unwrap();
    let p = project.to_str().unwrap();
    m.json(&[
        "use",
        "app-store-releaser",
        "--into",
        "claude-code",
        "--project",
        p,
    ]);
    let installed = snapshot(&project);

    // Another machine, with no sources at all, and only the committed record.
    let other = Machine::new();
    let clone = other.path("clone");
    std::fs::create_dir_all(&clone).unwrap();
    std::fs::copy(project.join("rolesmith.toml"), clone.join("rolesmith.toml")).unwrap();
    other.json(&["sync", "--project", clone.to_str().unwrap()]);
    assert_eq!(snapshot(&clone), installed);
    let sources = std::fs::read_to_string(other.path("config/rolesmith/sources.toml")).unwrap();
    assert!(sources.contains(lib.url()), "{sources}");
}

#[test]
fn a_new_rev_deletes_only_the_generated_files_it_no_longer_has() {
    let m = Machine::new();
    let (lib, first) = published(&m, "felix", &["app-store-releaser"]);
    std::fs::remove_dir_all(lib.work.join("roles/app-store-releaser/skills")).unwrap();
    let second = m.publish(&lib, "no skills");
    m.json(&["source", "add", "felix", lib.url()]);
    let project = m.path("project");
    own_files(&project);
    let p = project.to_str().unwrap();
    let use_at = |rev: &str| {
        m.json(&[
            "use",
            "app-store-releaser",
            "--into",
            "claude-code",
            "--project",
            p,
            "--rev",
            rev,
        ])
    };

    use_at(&first);
    let skill_dir = project.join(".claude/skills/rolesmith-app-store-releaser-submit-build");
    assert!(skill_dir.join("SKILL.md").is_file());

    let out = use_at(&second);
    assert_eq!(
        out["removed"],
        serde_json::json!([".claude/skills/rolesmith-app-store-releaser-submit-build/SKILL.md"])
    );
    assert!(!skill_dir.exists());
    assert!(text(&project, "rolesmith.toml").contains(&second));
    assert!(!text(&project, ".gitignore").contains("submit-build"));
    assert_eq!(
        text(&project, ".claude/skills/my-own/SKILL.md"),
        "---\nname: my-own\ndescription: Mine.\n---\n\nMine.\n"
    );
    assert_eq!(
        text(&project, "CLAUDE.md"),
        "# My project\n\nKeep it small.\n"
    );
    assert_eq!(text(&project, "AGENTS.md"), "Agents: read CLAUDE.md.\n");
}

#[test]
fn a_file_rolesmith_did_not_generate_is_never_overwritten() {
    let m = Machine::new();
    let (lib, _) = published(&m, "felix", &["app-store-releaser"]);
    m.json(&["source", "add", "felix", lib.url()]);
    let project = m.path("project");
    let mine = project.join(".claude/skills/rolesmith-app-store-releaser/SKILL.md");
    std::fs::create_dir_all(mine.parent().unwrap()).unwrap();
    std::fs::write(&mine, "mine\n").unwrap();
    let p = project.to_str().unwrap();

    let o = m.rolesmith(&[
        "use",
        "app-store-releaser",
        "--into",
        "claude-code",
        "--project",
        p,
    ]);
    assert_eq!(o.status.code(), Some(1));
    assert!(stderr(&o).contains("will not overwrite"), "{}", stderr(&o));
    assert_eq!(std::fs::read_to_string(&mine).unwrap(), "mine\n");
    assert!(
        !project.join("rolesmith.toml").exists(),
        "the record is put back"
    );
}

#[test]
fn emptying_the_record_deletes_the_manifest_and_gitignore_and_keeps_the_skill_directory() {
    let m = Machine::new();
    let (lib, _) = published(&m, "felix", &["app-store-releaser"]);
    m.json(&["source", "add", "felix", lib.url()]);
    let project = m.path("project");
    std::fs::create_dir_all(&project).unwrap();
    let p = project.to_str().unwrap();
    m.json(&[
        "use",
        "app-store-releaser",
        "--into",
        "claude-code",
        "--project",
        p,
    ]);

    std::fs::write(project.join("rolesmith.toml"), "").unwrap();
    let out = m.json(&["sync", "--project", p]);
    assert_eq!(out["removed"].as_array().unwrap().len(), 4, "{out}");
    assert!(!project.join(".rolesmith").exists(), "{out}");
    assert!(
        !project.join(".gitignore").exists(),
        "rolesmith made it, so it goes"
    );
    let skills = project.join(".claude/skills");
    assert!(skills.is_dir(), "the target's skill directory stays");
    assert_eq!(std::fs::read_dir(&skills).unwrap().count(), 0);
}

#[test]
fn a_record_that_disagrees_with_the_machine_or_itself_is_refused() {
    let m = Machine::new();
    let (felix, rev) = published(&m, "felix", &["rust-cli"]);
    let (team, _) = published(&m, "team", &["rust-cli"]);
    m.json(&["source", "add", "felix", felix.url()]);
    m.json(&["source", "add", "team", team.url()]);
    let project = m.path("project");
    std::fs::create_dir_all(&project).unwrap();
    let p = project.to_str().unwrap();
    let refused = |args: &[&str], why: &str| {
        let o = m.rolesmith(args);
        assert_eq!(o.status.code(), Some(1), "{args:?}");
        assert!(stderr(&o).contains(why), "{args:?}: {}", stderr(&o));
    };

    m.json(&[
        "use",
        "felix/rust-cli",
        "--into",
        "claude-code",
        "--project",
        p,
    ]);
    refused(
        &[
            "use",
            "team/rust-cli",
            "--into",
            "claude-code",
            "--project",
            p,
        ],
        "already records rust-cli from source felix",
    );

    let record = |url: &str, rev: &str| {
        std::fs::write(
            project.join("rolesmith.toml"),
            format!(
                "[[role]]\nname = \"rust-cli\"\nsource = \"felix\"\nurl = \"{url}\"\nrev = \"{rev}\"\ninto = [\"claude-code\"]\n"
            ),
        )
        .unwrap();
    };
    record(team.url(), &rev);
    refused(&["sync", "--project", p], "but this machine has it as");
    record(felix.url(), &rev[..8]);
    refused(&["sync", "--project", p], "is not a full commit SHA");
}
