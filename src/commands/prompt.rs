//! `rolesmith prompt <role> [--rev <sha>]`: a role as one Markdown document for an agent that takes
//! instructions but reads no skills (SPEC.md §5.3). It writes nothing.

use serde_json::{Value, json};

use super::{Command, Failure, Output};
use crate::library::{Library, Role};

/// The role as one Markdown document: core, prohibitions, then each skill's description and path.
#[derive(clap::Args)]
#[group(skip)]
pub struct Args {
    #[command(flatten)]
    pub at: super::show::Args,
}

impl Command for Args {
    const NAME: &'static str = "prompt";

    fn output_shape() -> Value {
        json!({
            "$schema": "https://json-schema.org/draft/2020-12/schema",
            "type": "object",
            "required": ["role", "rev", "markdown"],
            "properties": {
                "role": { "type": "string", "description": "<source>/<role>" },
                "rev": { "type": "string", "description": "the full SHA the role was read at" },
                "markdown": { "type": "string", "description": "the document the human form prints" }
            }
        })
    }

    fn run(self) -> Result<Output, Failure> {
        let (found, lib, _tree) = self.at.read()?;
        let role = &lib.roles[0];
        // Loaded for one role, the library holds it first and then every role it requires.
        let requires = &lib.roles[1..];
        let mut md = format!(
            "<!-- Generated by rolesmith from {} at {}; do not edit. -->\n\n",
            found.qualified(),
            found.rev
        );
        if !requires.is_empty() {
            let names: Vec<&str> = requires.iter().map(|r| r.name.as_str()).collect();
            md.push_str(&format!(
                "This role builds on {}: their core, prohibitions and skills follow its own, and are \
                 in force too.\n\n",
                names.join(", ")
            ));
        }
        let intro = format!(
            "When a task matches a skill's description, read its full text: the path is in the \
             source {} at {}.\n\n",
            found.source, found.rev
        );
        md.push_str(&section(&lib, role, &intro));
        for r in requires {
            md.push_str(&format!(
                "\n# Required role {}/{}: {}\n\n{}",
                found.source,
                r.name,
                r.toml.description,
                section(&lib, r, "")
            ));
        }
        let json = json!({ "role": found.qualified(), "rev": found.rev, "markdown": md });
        Ok(Output { json, human: md })
    }
}

/// A role's core, its prohibitions, then `intro` and each skill's name, description and path in
/// the library.
fn section(lib: &Library, role: &Role, intro: &str) -> String {
    let mut md = format!("{}\n\n## Prohibitions\n\n", role.core.trim_end());
    for p in &role.prohibitions {
        md.push_str(&format!("- {} ({})\n", p.rule, p.why));
    }
    md.push_str("\n## Skills\n\n");
    md.push_str(intro);
    for s in &role.skills {
        let place = match &s.external {
            Some(e) => format!("`{}/SKILL.md` in {} at {}", e.path, e.url, e.rev),
            None => {
                let dir = s.dir.strip_prefix(&lib.root).unwrap_or(&s.dir);
                format!("`{}`", dir.join("SKILL.md").display())
            }
        };
        md.push_str(&format!("- {}: {} ({place})\n", s.name, s.description));
    }
    md
}
