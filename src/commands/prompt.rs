//! `rolesmith prompt <role> [--rev <sha>]`: a role as one Markdown document for an agent that takes
//! instructions but reads no skills (SPEC.md §5.3). It writes nothing.

use serde_json::{Value, json};

use super::{Command, Failure, Output};
use crate::library::{Library, Role};
use crate::sources::{self, Found, Sources};

/// The role as one Markdown document: core, prohibitions, then each skill's description and path.
#[derive(clap::Args)]
pub struct Args {
    /// The role: <role> when one source has it, <source>/<role> otherwise.
    pub role: String,

    /// Read the role at this commit of its source instead of its local main.
    #[arg(long, value_name = "SHA")]
    pub rev: Option<String>,
}

impl Command for Args {
    const NAME: &'static str = "prompt";

    fn output_shape() -> Value {
        json!({
            "$schema": "https://json-schema.org/draft/2020-12/schema",
            "type": "object",
            "required": ["role", "rev", "markdown"],
            "properties": {
                "role": { "type": "string", "description": "<source>/<role>" },
                "rev": { "type": "string", "description": "the full SHA the role was read at" },
                "markdown": { "type": "string", "description": "the document the human form prints" }
            }
        })
    }

    fn run(self) -> Result<Output, Failure> {
        let record = Sources::load()?;
        let found = sources::resolve(&record, &self.role, self.rev.as_deref())?;
        let (lib, _tree) = sources::read_role(&found)?;
        let markdown = document(&found, &lib, &lib.roles[0]);
        let json = json!({
            "role": found.qualified(),
            "rev": found.rev,
            "markdown": markdown,
        });
        Ok(Output {
            json,
            human: markdown,
        })
    }
}

/// The document: a generated-from line, the core, the prohibitions, the skills with the path of
/// each one's full text in the source.
fn document(found: &Found, lib: &Library, role: &Role) -> String {
    let mut md = format!(
        "<!-- Generated by rolesmith from {} at {}; do not edit. -->\n\n",
        found.qualified(),
        found.rev
    );
    md.push_str(&format!("{}\n\n## Prohibitions\n\n", role.core.trim_end()));
    if role.prohibitions.is_empty() {
        md.push_str("(none)\n");
    }
    for p in &role.prohibitions {
        md.push_str(&format!("- {} ({})\n", p.rule, p.why));
    }
    md.push_str(&format!(
        "\n## Skills\n\nWhen a task matches a skill's description, read its full text: the path is in \
         the source {} at {}.\n\n",
        found.source, found.rev
    ));
    if role.skills.is_empty() {
        md.push_str("(none)\n");
    }
    for s in &role.skills {
        let dir = s.dir.strip_prefix(&lib.root).unwrap_or(&s.dir);
        md.push_str(&format!(
            "- {}: {} (`{}`)\n",
            s.name,
            s.description,
            dir.join("SKILL.md").display()
        ));
    }
    md
}
